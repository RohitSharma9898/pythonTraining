"""
====================================================
             ITERATORS AND GENERATORS
====================================================

ITERABLE:
An object that we can iterate over.

Examples:

list
tuple
string
set
dictionary

Example:

numbers = [10, 20, 30]

We can use a for loop on it.


ITERATOR:
An iterator is an object that gives us
one value at a time.

We can create an iterator using:

iter()


GENERATOR:
A generator is a simple way to create
an iterator using the yield keyword.


Main idea:

Iterable
   ↓
Iterator
   ↓
One value at a time
"""