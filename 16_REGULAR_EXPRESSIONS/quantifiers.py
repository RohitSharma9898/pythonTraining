"""
====================================================
                  QUANTIFIERS
====================================================

Quantifiers tell regex HOW MANY times
a pattern should occur.
"""


import re


# ==================================================
# * -> ZERO OR MORE
# ==================================================

text = "ab a abbb"


print(re.findall(r"ab*", text))


# ==================================================
# + -> ONE OR MORE
# ==================================================

text = "a ab abb abbb"


print(re.findall(r"ab+", text))


# ==================================================
# ? -> ZERO OR ONE
# ==================================================

text = "color colour"


print(re.findall(r"colou?r", text))


# ==================================================
# {n} -> EXACTLY n TIMES
# ==================================================

text = "123 1234 12345"


print(re.findall(r"\d{3}", text))


# ==================================================
# {n,m} -> BETWEEN n AND m TIMES
# ==================================================

text = "12 123 1234 12345"


print(re.findall(r"\d{2,4}", text))