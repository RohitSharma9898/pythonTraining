"""
====================================================
              MODULES AND PACKAGES
====================================================

MODULE:
A Python file containing Python code.

A module can contain:

- Variables
- Functions
- Classes

Example:

math_tools.py

We can import math_tools into another
Python file and use its code.

----------------------------------------------------

PACKAGE:

A package is a folder containing
Python modules.

Real-life example:

project/
│
├── calculator.py
├── students.py
└── employees.py

These files are modules.

A folder containing related modules
can be organized as a package.
"""