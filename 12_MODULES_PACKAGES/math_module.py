"""
MATH MODULE
"""

import math


# Absolute value

print(math.fabs(-10))


# Square root

print(math.sqrt(49))


# Power

print(math.pow(2, 5))


# Ceiling

print(math.ceil(4.2))


# Floor

print(math.floor(4.8))


# Factorial

print(math.factorial(5))


# Greatest common divisor

print(math.gcd(12, 18))