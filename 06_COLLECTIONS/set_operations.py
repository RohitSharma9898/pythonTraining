"""
SET OPERATIONS

Set:
- Unordered
- Mutable
- No duplicate values
"""

A = {1, 2, 3, 4}
B = {3, 4, 5, 6}


# ==========================================
# UNION
# ==========================================

print("Union:", A | B)


# ==========================================
# INTERSECTION
# ==========================================

print("Intersection:", A & B)


# ==========================================
# DIFFERENCE
# ==========================================

print("A - B:", A - B)

print("B - A:", B - A)


# ==========================================
# SYMMETRIC DIFFERENCE
# ==========================================

print("Symmetric Difference:", A ^ B)


# ==========================================
# SUBSET
# ==========================================

A = {1, 2, 3, 4}
B = {1, 2}

print(B.issubset(A))


# ==========================================
# SUPERSET
# ==========================================

print(A.issuperset(B))


# ==========================================
# DISJOINT
# ==========================================

C = {10, 20}

print(A.isdisjoint(C))