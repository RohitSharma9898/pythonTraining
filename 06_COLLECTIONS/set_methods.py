"""
IMPORTANT SET METHODS
"""

numbers = {10, 20, 30}


# ==========================================
# add()
# ==========================================

numbers.add(40)

print(numbers)


# ==========================================
# update()
# ==========================================

numbers.update([50, 60])

print(numbers)


# ==========================================
# remove()
# ==========================================

numbers.remove(60)

print(numbers)


# ==========================================
# discard()
# ==========================================

numbers.discard(100)

print(numbers)


# ==========================================
# pop()
# ==========================================

removed = numbers.pop()

print("Removed:", removed)
print(numbers)


# ==========================================
# copy()
# ==========================================

new_numbers = numbers.copy()

print(new_numbers)


# ==========================================
# clear()
# ==========================================

numbers.clear()

print(numbers)


