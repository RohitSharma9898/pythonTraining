"""
IMPORTANT DICTIONARY METHODS
"""

student = {
    "name": "Rohit",
    "age": 21,
    "marks": 90
}


# ==========================================
# keys()
# ==========================================

print(student.keys())


# ==========================================
# values()
# ==========================================

print(student.values())


# ==========================================
# items()
# ==========================================

print(student.items())


# ==========================================
# get()
# ==========================================

print(student.get("name"))


# ==========================================
# update()
# ==========================================

student.update({
    "marks": 95,
    "city": "Vadodara"
})

print(student)


# ==========================================
# pop()
# ==========================================

removed = student.pop("city")

print("Removed:", removed)
print(student)


# ==========================================
# popitem()
# ==========================================

removed_item = student.popitem()

print("Removed:", removed_item)
print(student)


# ==========================================
# setdefault()
# ==========================================

student.setdefault("course", "Python")

print(student)


# ==========================================
# copy()
# ==========================================

new_student = student.copy()

print(new_student)


# ==========================================
# clear()
# ==========================================

student.clear()

print(student)