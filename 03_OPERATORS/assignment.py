"""
ASSIGNMENT OPERATORS

Assignment operators are used to assign
and update values.

=
+=
-=
*=
/=
//=
%=
**=
"""

# ==========================================
# BASIC ASSIGNMENT
# ==========================================

x = 10

print(x)


# ==========================================
# ADD AND ASSIGN
# ==========================================

x = 10

x += 5

print("x += 5:", x)


# Same as:
# x = x + 5


# ==========================================
# SUBTRACT AND ASSIGN
# ==========================================

x = 10

x -= 3

print("x -= 3:", x)


# Same as:
# x = x - 3


# ==========================================
# MULTIPLY AND ASSIGN
# ==========================================

x = 10

x *= 2

print("x *= 2:", x)


# ==========================================
# DIVIDE AND ASSIGN
# ==========================================

x = 20

x /= 4

print("x /= 4:", x)


# ==========================================
# FLOOR DIVIDE AND ASSIGN
# ==========================================

x = 20

x //= 3

print("x //= 3:", x)


# ==========================================
# MODULUS AND ASSIGN
# ==========================================

x = 20

x %= 6

print("x %= 6:", x)


# ==========================================
# POWER AND ASSIGN
# ==========================================

x = 2

x **= 3

print("x **= 3:", x)


# ==========================================
# PRACTICAL EXAMPLE
# ==========================================

balance = 10000

balance += 5000
print("After deposit:", balance)

balance -= 2000
print("After withdrawal:", balance)