"""
BITWISE OPERATORS

Bitwise operators work at the binary/bit level.

Operators:

&   AND
|   OR
^   XOR
~   NOT
<<  Left Shift
>>  Right Shift
"""

a = 10
b = 4

"""
Binary representation:

10 = 1010
4  = 0100
"""


# ==========================================
# BITWISE AND
# ==========================================

print("AND:", a & b)

"""
  1010
& 0100
------
  0000

Result = 0
"""


# ==========================================
# BITWISE OR
# ==========================================

print("OR:", a | b)

"""
  1010
| 0100
------
  1110

Result = 14
"""


# ==========================================
# BITWISE XOR
# ==========================================

print("XOR:", a ^ b)

"""
  1010
^ 0100
------
  1110

Result = 14
"""


# ==========================================
# BITWISE NOT
# ==========================================

print("NOT:", ~a)

"""
Important:

~x = -(x + 1)

~10 = -(10 + 1)
    = -11
"""

print(~10)
print(~5)
print(~0)


# ==========================================
# LEFT SHIFT
# ==========================================

x = 5

print("Left shift:", x << 1)

"""
5 = 0101

0101 << 1
---------
1010

1010 = 10
"""


# ==========================================
# RIGHT SHIFT
# ==========================================

x = 10

print("Right shift:", x >> 1)

"""
10 = 1010

1010 >> 1
---------
0101

0101 = 5
"""


# ==========================================
# MORE EXAMPLES
# ==========================================

a = 12
b = 7

print("a & b =", a & b)
print("a | b =", a | b)
print("a ^ b =", a ^ b)
print("~a =", ~a)
print("a << 1 =", a << 1)
print("a >> 1 =", a >> 1)


# ==========================================
